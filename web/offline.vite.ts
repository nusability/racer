// Vite plugin: makes the game playable offline. After the build it writes sw.js, a service
// worker that precaches every file of that build (the game, the level viewer, fonts, thumbnails,
// icons; about 2.5 MB) under a cache named after the build stamp. A new deploy is a new cache:
// the browser installs it in the background when online and drops the old one, so players never
// run a mix of two builds.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

/** Files the worker must not cache: itself (the browser fetches it fresh to look for updates). */
const NOT_CACHED = new Set(['sw.js']);

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

export function offline(build: string): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'mirage-offline',
    apply: 'build',
    configResolved(c) {
      config = c;
    },
    closeBundle() {
      const outDir = join(config.root, config.build.outDir);
      const files = listFiles(outDir)
        .map((f) => relative(outDir, f).split(sep).join('/'))
        .filter((f) => !NOT_CACHED.has(f))
        .sort();
      if (!files.includes('index.html')) throw new Error('offline: build has no index.html to cache');
      writeFileSync(join(outDir, 'sw.js'), serviceWorker(build, files));
    },
  };
}

/**
 * The worker itself. Cache first for everything this build shipped (hashed assets never change
 * under one name); pages are matched without their query string so ?track=… still works offline.
 * './' is cached as index.html because that is what the server answers for the start URL.
 */
function serviceWorker(build: string, files: string[]): string {
  return `// Generated by offline.vite.ts for build ${build}. Do not edit.
const CACHE = ${JSON.stringify(`mirage-racer ${build}`)};
const FILES = ${JSON.stringify(['./', ...files.map((f) => `./${f}`)])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

// Older builds' caches go only once a page runs on this build ('prune' from src/offline.ts):
// until then a page still on the previous build keeps finding its files.
self.addEventListener('message', (event) => {
  if (event.data !== 'prune') return;
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('mirage-racer ') && k !== CACHE).map((k) => caches.delete(k)))),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // Every Mirage cache is searched, so a page still running the previous build finds its files
  // until it reloads onto the new one.
  // ignoreVary: module scripts load with crossorigin, so they carry an Origin header the cached
  // copies were fetched without; servers that answer 'Vary: Origin' would otherwise never match.
  event.respondWith(caches.match(req, { ignoreSearch: req.mode === 'navigate', ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`;
}
